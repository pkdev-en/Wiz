"""gen_template906.py - translate the Lapis ML620Q906 boot template (symbolic SFR names, LEA)
into template_ML620906.asm with raw addresses, the same style as template_ML620909.asm.

Strict: every name is looked up in the 906 DCL; the four names the DCL does not define are listed
in INFERRED with the evidence, and are written into the header of the generated file.

    python3 tools/gen_template906.py            # rewrites ../template_ML620906.asm
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
NEEDED_REGS = ['DSR', 'FCON', 'BLKCON0', 'IE0', 'TM0CON', 'TM0C', 'TM0D', 'TM0CON1', 'IRQ0', 'IRQ2',
               'STPACP', 'SBYCON', 'P1D', 'P0D', 'KICON', 'KOD']
NEEDED_BITS = ['DTM0', 'ETM0']
# names used by the template but NOT defined in the 906 DCL we have:
INFERRED = {
    'XTM0':   ('0F00AH.0', 'FCON.0 = LOSCEN in the DCL; the 909 boot does the same thing as "ST 81H -> 0F00AH"'),
    'XTM1':   ('0F00AH.1', 'FCON.1 = LOSCM in the DCL; the 909 boot clears 0F00AH.1 in the same spot'),
    'KIMASK': ('0F042H',   'libcw.h KeyboardInMask = 0xF042 (DCL calls it KIMOD); 909 boot writes 0 there'),
    'KOMASK': ('0F044H',   'libcw.h KeyboardOutMask = 0xF044 (DCL calls it KOCON); 909 boot writes 80H,0FFH there'),
}


def load_dcl(path):
    regs, bits = {}, {}
    for line in open(path, encoding='latin-1').read().replace('\r', '').split('\n'):
        m = re.match(r'^\s*([A-Za-z_]\w*)\s+([0-9][0-9A-F]*H)\s*(?:;.*)?$', line)
        if m and m.group(1) not in regs:
            regs[m.group(1)] = m.group(2)
        m = re.match(r'^\s*([A-Za-z_]\w*)\s+([A-Za-z_]\w*)\.([0-7])\s*(?:;.*)?$', line)
        if m and m.group(1) not in bits:
            bits[m.group(1)] = (m.group(2), m.group(3))
    return regs, bits


def main():
    regs, bits = load_dcl(os.path.join(HERE, 'originals', 'ML620906.DCL'))
    table = {}
    for n in NEEDED_REGS:
        assert n in regs, 'DCL has no %s' % n
        table[n.upper()] = regs[n]
    for n in NEEDED_BITS:
        assert n in bits, 'DCL has no bit %s' % n
        reg, b = bits[n]
        table[n.upper()] = '%s.%s' % (regs[reg], b)
    for n, (v, _) in INFERRED.items():
        table[n.upper()] = v
    src = open(os.path.join(HERE, 'originals', 'ML620Q906.asm'), encoding='latin-1').read().replace('\r', '')
    out = []
    used = set()
    for line in src.split('\n'):
        code, sep, comment = line.partition(';')

        def sub(m):
            k = m.group(0).upper()
            if k in table:
                used.add(k)
                return table[k]
            return m.group(0)
        code = re.sub(r'[A-Za-z_][A-Za-z0-9_]*', sub, code)
        code = code.replace('[ea+]', '[EA+]').replace('[ea]', '[EA]')
        out.append(code + (sep + comment if sep else ''))
    text = '\n'.join(out).rstrip() + '\n'
    assert text.rstrip().endswith(';start your program here')
    text = text.rstrip() + '\n\tb _main\n'
    header = ['; ML620906 boot, generated by tools/gen_template906.py from ML620Q906.asm + the 906 DCL.',
              '; Symbol names were replaced by raw SFR addresses. Names the DCL does not define (inferred):']
    for n, (v, why) in INFERRED.items():
        header.append(';   %-7s = %-9s %s' % (n, v, why))
    header.append('')
    open(os.path.join(HERE, '..', 'template_ML620906.asm'), 'w').write('\n'.join(header) + '\n' + text)
    print('translated names:', ', '.join(sorted(used)))
    missing = set(table) - used
    print('unused table entries:', ', '.join(sorted(missing)) or 'none')


if __name__ == '__main__':
    main()
